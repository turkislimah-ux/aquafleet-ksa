/** Issued = left draft/review, so it renders from frozen columns. */
const ISSUED = new Set(["confirmed", "paid", "void"]);

type Divergence = {
  invoice: string;
  status: string;
  storedCovered: number;
  derivedCovered: number;
  storedDue: number;
  derivedDue: number;
};

/**
 * Re-derive one invoice's covered/unpaid split through the CURRENT engine.
 *
 * Mirrors app/trips/invoiceActions.ts `assembleForCustomerPeriod` input
 * assembly exactly — anything looser manufactures divergences that the
 * production path would never produce:
 *   - trips are the customer's WHOLE history, not period-filtered (the
 *     PERIOD-MEMBERSHIP RULE), rate frozen-first;
 *   - top-ups and returns are lifetime, ungated;
 *   - specialCharges is every charge on every NON-VOID invoice of the
 *     customer, not just this invoice's own;
 *   - reservedElsewhereIds = trips/charges claimed by a DIFFERENT invoice.
 */
function rederive(inv: InvoiceRow): Divergence | null {
  const [invKey, custKey, status, periodStart, periodEnd, storedCovered, storedDue] = inv;
  const customer = CUSTOMERS.find((c) => c[0] === custKey);
  if (!customer) throw new Error(`fixture: no customer ${custKey} for invoice ${invKey}`);

  const custTrips = TRIPS.filter((t) => t[1] === custKey);
  const trips: ConsumingTrip[] = custTrips.map((t) => ({
    id: t[0],
    trip_date: t[2],
    delivered_at: t[3],
    rate_sar: t[4],
    ref: null,
    water_type: null,
  }));
  const topups: TopupLite[] = TOPUPS.filter((t) => t[1] === custKey).map((t) => ({
    id: t[0],
    amount_sar: t[2],
    topup_date: t[3],
  }));
  const returns: BalanceReturnLite[] = RETURNS.filter((r) => r[1] === custKey).map((r) => ({
    id: r[0],
    amount_sar: r[2],
    returned_on: r[3],
  }));

  const custChargeRows = CHARGES.filter((c) => {
    const owner = INVOICES.find((i) => i[0] === c[1]);
    return owner != null && owner[1] === custKey && owner[2] !== "void";
  });
  const specialCharges: SpecialChargeInput[] = custChargeRows.map((c) => ({
    id: c[0],
    label: c[2],
    amount_sar: c[3],
    charge_date: c[4],
    created_at: c[5],
  }));

  const reservedElsewhereIds = [
    ...custTrips.filter((t) => t[5] != null && t[5] !== invKey).map((t) => t[0]),
    ...custChargeRows.filter((c) => c[1] !== invKey).map((c) => c[0]),
  ];

  const assembly = assembleInvoice({
    customerId: custKey,
    paymentMode: customer[2] as PaymentMode,
    periodStart,
    periodEnd,
    trips,
    topups,
    returns,
    specialCharges,
    reservedElsewhereIds,
  });

  const derivedCovered = round2(assembly.covered.total);
  const derivedDue = round2(assembly.amountDue.total);
  if (derivedCovered === round2(storedCovered) && derivedDue === round2(storedDue)) return null;
  return { invoice: invKey, status, storedCovered, derivedCovered, storedDue, derivedDue };
}

