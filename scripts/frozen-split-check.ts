// Guard for the FROZEN-vs-RE-DERIVED invoice split. No test framework.
// Run:  npx tsx scripts/frozen-split-check.ts
// Exits 0 if every assertion passes, 1 otherwise (CI-friendly).
//
// ---------------------------------------------------------------------------
// WHY THIS FILE EXISTS
//
// `.claude/skills/aquafleet-domain/SKILL.md` §"Frozen invoice splits diverging
// from a re-derivation is EXPECTED" records that a handful of already-issued
// prepaid invoices would land on a DIFFERENT covered/unpaid boundary if the
// current engine re-ran them — because `9c287d6` + `dc29e26` made the prepaid
// pool a LIFETIME NET (asOfDate scopes consumption only), so top-ups dated
// after an invoice's periodEnd now enlarge the pool that invoice's split walks.
// Turki ruled LEAVE. This file makes that ruling self-verifying instead of
// something that gets rebuilt from a throwaway script every time it is
// questioned (which happened twice in one session).
//
// WHAT IT ASSERTS vs WHAT IT PRINTS
//
//   ASSERTS (exit code): every divergent invoice is ISSUED — confirmed, paid or
//   void — and the issued render path reads the FROZEN columns rather than
//   re-deriving. Together those two are the whole claim: the divergence exists
//   in arithmetic and is never visible on a document.
//
//   PRINTS (informational, never asserted): the count and the SAR total that
//   would move Unpaid -> Covered. Those are a DATED MEASUREMENT and will drift
//   the moment anyone adds a prepaid invoice or a top-up. Hardcoding them would
//   make this a brittle test, not a guard.
//
// THIS HARNESS PRINTS 10 / 28,474.00 SAR. SKILL.md's annotation, measured the
// same day by a throwaway script, says 8 / 13,524.00. Neither is asserted and
// the gap is METHOD, not data: this file re-derives a void invoice too, and a
// void's lines were RELEASED back to the pool and re-picked by later invoices,
// so it re-derives to ~nothing and books its whole stored amount_due as
// "moved". Invoices 1 (void, 11,500.00), 026-000006 and 2 account for the
// 14,950.00 gap. Read the per-invoice lines, never the total alone. The ruling
// (LEAVE) does not depend on which figure is right — see assertion 1.
//
// FIXTURE, NOT A LIVE READ — matching every other money harness here. The anon
// key in `.env.local` cannot read trips/invoices/topups (42501) and there is no
// service-role key in the repo, so live rows are pulled through the Supabase MCP
// and embedded below. Re-pull with the query in REFRESHING THE FIXTURE.
//
// PREPAID-NESS RESOLVER. Rows are selected by the expression behind
// `v_invoice_outstanding_live.effective_payment_mode`:
//     coalesce(invoices.payment_mode, <the customer's single distinct
//              projects.payment_mode>)
// NOT `invoices.payment_mode` on its own — that column is NULL on every row
// predating migration 0037, so `where payment_mode = 'prepaid'` silently drops
// invoices INCLUDING all the void ones, and an undercount reads exactly like a
// clean result. The view itself cannot be joined for this: it filters to
// confirmed-AND-unpaid-AND-not-void, which is the opposite of the population we
// need. So the resolver EXPRESSION is reused, not the view.
//
// IDS ARE SHORT SYNTHETIC KEYS, ORDER-EQUIVALENT TO THE REAL UUIDS. The engine
// only ever compares ids as a LAST tiebreak, between two trips sharing both
// `trip_date` and `delivered_at` (see compareConsumedItems). Trip keys are
// assigned by `row_number() over (order by trip_date, delivered_at, id)`, so
// within any such tie the synthetic order equals the uuid order by
// construction. Everything the money depends on — dates, rates, invoice
// attachment — is carried verbatim.
// ---------------------------------------------------------------------------
//
// REFRESHING THE FIXTURE (Supabase MCP `execute_sql`, project ceqzmztewbborwgxnrqh):
//
//   with eff as (
//     select i.id, i.customer_id, coalesce(i.payment_mode, pm.resolved_mode) as eff_mode
//     from public.invoices i
//     left join lateral (
//       select case when count(distinct p.payment_mode) = 1 then min(p.payment_mode) end as resolved_mode
//       from public.projects p
//       where p.customer_id = i.customer_id and p.payment_mode is not null) pm on true
//   ), pc as (select distinct customer_id from eff where eff_mode = 'prepaid'),
//   ck as (select c.id, 'C' || row_number() over (order by c.id) as key
//          from public.customers c where c.id in (select customer_id from pc)),
//   ik as (select i.id, coalesce(i.invoice_number, 'X' || left(i.id::text, 4)) as key
//          from public.invoices i join ck on ck.id = i.customer_id),
//   tr as (select ck.key ck, t.id, t.trip_date, t.delivered_at, t.invoice_id,
//                 coalesce(t.rate_sar, p.rate_per_trip_sar) rate
//          from public.trips t join public.projects p on p.id = t.project_id
//          join ck on ck.id = p.customer_id),
//   tord as (select tr.*, 't' || lpad((row_number() over
//              (order by tr.trip_date, tr.delivered_at nulls last, tr.id))::text, 3, '0') as key from tr)
//   select json_agg(json_build_array(tord.key, tord.ck, tord.trip_date::text,
//            tord.delivered_at::text, tord.rate, ik.key) order by tord.key)
//   from tord left join ik on ik.id = tord.invoice_id;
//
// (the customers / invoices / topups / returns / charges arrays come from the
// sibling json_build_object query in the same session — same CTE prefix.)

