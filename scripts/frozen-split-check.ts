// 2. THE INVARIANT — the freeze boundary: frozen <-> ISSUED.
//
// This is the half that makes the divergence harmless, and the half that can
// actually break. An invoice carries a frozen split if and only if it is issued
// (confirmed/paid/void). Consequences both ways:
//   - issued AND NOT frozen  => it renders from frozen columns that were never
//     written: a document prints zeros. A real, visible defect.
//   - frozen AND NOT issued  => a draft/review row is carrying a stale snapshot
//     it will never show, and freeze-at-confirm fired somewhere it should not.
// Divergence is invisible precisely because the two render paths and the two
// storage states line up: issued reads stored, draft/review re-derives live.
// Asserted on the SHAPE of the data, never on the divergence count.

/** Pure so the negative control below can drive it with synthetic rows. */
function freezeBoundaryBreaks(rows: InvoiceRow[]): string[] {
  return rows
    .filter((i) => i[9] !== ISSUED.has(i[2]))
    .map((i) => `${i[0]} (${i[2]}, frozen=${i[9]})`);
}

const breaks = freezeBoundaryBreaks(prepaidInvoices);
assert(
  "freeze boundary holds: an invoice is frozen if and only if it is issued",
  breaks.length === 0,
  `mismatched: ${breaks.join(", ")}`,
);

