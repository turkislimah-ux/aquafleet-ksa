// helper: window.T('nav.fleet') -> "Fleet" or "الأسطول"
window.T = function(path) {
  const lang = window.APP_STATE.lang;
  const parts = path.split(".");
  let n = window.DICT;
  for (const p of parts) n = n && n[p];
  if (!n) return path;
  return n[lang] ?? n.en ?? path;
};
